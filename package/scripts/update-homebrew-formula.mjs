import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));

/**
 * Every checked-in copy of the generated formula. The first is the canonical
 * checkout-install formula; the second is the staged copy that mirrors the
 * intended `assistant-ui/homebrew-riftri` tap repository layout (see
 * package/homebrew/README.md). They must stay byte-identical, which
 * package/test/homebrew-formula.test.js enforces.
 */
export const formulaPaths = [
  path.join(root, "Formula/riftri.rb"),
  path.join(root, "package/homebrew/Formula/riftri.rb"),
];

/** Release archives Homebrew installs from, in formula order. */
const bottles = [
  { archive: "riftri-darwin-arm64", os: "macos", arch: "arm" },
  { archive: "riftri-darwin-x64", os: "macos", arch: "intel" },
  { archive: "riftri-linux-arm64-gnu", os: "linux", arch: "arm" },
  { archive: "riftri-linux-x64-gnu", os: "linux", arch: "intel" },
];

/** Parse a `sha256sum` manifest into an archive-name keyed map. */
export function parseChecksums(contents) {
  const checksums = new Map();
  for (const line of contents.trimEnd().split("\n")) {
    const match = /^([0-9a-f]{64}) {2}([^/\\]+)$/.exec(line);
    if (!match) {
      throw new Error(`malformed SHA256SUMS line: ${line}`);
    }
    checksums.set(match[2], match[1]);
  }
  return checksums;
}

export function renderHomebrewFormula({ version, checksums }) {
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error(`expected a bare semantic version, received ${version}`);
  }
  const tag = `v${version}`;
  const resolved = bottles.map((bottle) => {
    const file = `${bottle.archive}-${tag}.tar.gz`;
    const sha = checksums.get(file);
    if (!sha) {
      throw new Error(`missing checksum for ${file}`);
    }
    return { ...bottle, file, sha };
  });

  const urlFor = (entry) =>
    `https://github.com/assistant-ui/riftri/releases/download/${tag}/${entry.file}`;
  const block = (entry, indent) =>
    [
      `${indent}url "${urlFor(entry)}"`,
      `${indent}sha256 "${entry.sha}"`,
    ].join("\n");
  const find = (os, arch) =>
    resolved.find((entry) => entry.os === os && entry.arch === arch);

  return `# Generated by package/scripts/update-homebrew-formula.mjs. Do not edit by hand.
class Riftri < Formula
  desc "Lightweight Git workspaces for parallel development"
  homepage "https://riftri.dev"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block(find("macos", "arm"), "      ")}
    end
    on_intel do
${block(find("macos", "intel"), "      ")}
    end
  end

  on_linux do
    on_arm do
${block(find("linux", "arm"), "      ")}
    end
    on_intel do
${block(find("linux", "intel"), "      ")}
    end
  end

  def install
    bin.install "riftri"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/riftri --version")
    system "git", "init", "--quiet", testpath/"repository"
    report = shell_output("#{bin}/riftri doctor #{testpath}/repository --json")
    assert_match "storage_capabilities", report
  end
end
`;
}

export async function updateHomebrewFormula({
  version,
  checksumsPath,
  targets = formulaPaths,
} = {}) {
  const contents = await readFile(checksumsPath, "utf8");
  const formula = renderHomebrewFormula({
    version,
    checksums: parseChecksums(contents),
  });
  for (const target of targets) {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, formula);
  }
  return targets;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const [version, checksumsPath] = process.argv.slice(2);
  if (!version || !checksumsPath) {
    throw new Error(
      "usage: node package/scripts/update-homebrew-formula.mjs <version> <SHA256SUMS path>",
    );
  }
  const written = await updateHomebrewFormula({ version, checksumsPath });
  process.stdout.write(`${written.join("\n")}\n`);
}
